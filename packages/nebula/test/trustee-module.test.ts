import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { gzipSync } from "node:zlib";
import { parse, stringify, type TomlTable } from "smol-toml";
import { App, Chart } from "cdk8s";
import {
  Trustee, TngTrustee, trusteePlan, tngTrusteePlan, trusteeInitData, tngTrusteeInitData,
  type TrusteeConfig, type TngTrusteeConfig,
} from "../src";
import { canonicalJson, sha256Hex } from "../src/modules/k8s/confidential-guests/canonical";
import { INIT_DATA_ANNOTATION, initDataDocument, initDataSha256 } from "../src/modules/k8s/confidential-guests/measured";
import { synthOf } from "./support/cdk8s-render";

type Fixture = ({ mode: "bootstrap"; config: TrusteeConfig } | { mode: "tng"; config: TngTrusteeConfig }) & {
  planSha256: string;
  initDataSha256: string;
  manifestsSha256: string;
};
const baseline = JSON.parse(readFileSync(new URL("./fixtures/trustee-module-compatibility.json", import.meta.url), "utf8")) as {
  policyRego: string;
  fixtures: Fixture[];
};

// These expected values were recorded from the old module, not generated by
// the implementation under test. Plans and InitData must remain byte-stable:
// changing them invalidates an owner's previously reviewed workload identity.
for (const fixture of baseline.fixtures) {
  test(`${fixture.mode} preserves measured output with createNamespace=${fixture.config.createNamespace ?? true}`, () => {
    const plan = fixture.mode === "tng" ? tngTrusteePlan(fixture.config) : trusteePlan(fixture.config);
    const reviewed = { canonicalPodSha256: plan.canonicalPodSha256, policyRego: baseline.policyRego };
    const policy = fixture.mode === "tng" ? tngTrusteeInitData(fixture.config, reviewed) : trusteeInitData(fixture.config, reviewed);
    const before = structuredClone(fixture.config);
    const { objects } = synthOf(chart => {
      const module = fixture.mode === "tng"
        ? new TngTrustee(chart, "trustee", { ...fixture.config, policy })
        : new Trustee(chart, "trustee", { ...fixture.config, policy });
      assert.equal(module.namespace?.name, fixture.config.createNamespace === false ? undefined : fixture.config.namespace);
      assert.equal(module.deployment.name, fixture.config.name);
      assert.equal(module.service.name, fixture.config.name);
      assert.equal(module.networkPolicy.name, fixture.config.name);
      assert.equal(module.initDataSha256, policy.initDataSha256);
    });
    assert.deepEqual(fixture.config, before, "composition must not mutate the caller's configuration");
    assert.equal(sha256Hex(canonicalJson(plan)), fixture.planSha256, "unsigned plan changed");
    assert.equal(policy.initDataSha256, fixture.initDataSha256, "measured InitData document changed");
    assert.equal(initDataSha256(policy.ccInitData), fixture.initDataSha256, "annotation must carry that exact document");
    // Gzip output varies with Node's zlib version; hardware measures the
    // decompressed document. Compare that identity in the transport annotation.
    for (const object of objects) {
      const annotations = object.spec?.template?.metadata?.annotations;
      if (annotations?.[INIT_DATA_ANNOTATION]) annotations[INIT_DATA_ANNOTATION] = initDataSha256(annotations[INIT_DATA_ANNOTATION]);
    }
    assert.equal(sha256Hex(canonicalJson(objects)), fixture.manifestsSha256, "rendered Kubernetes resources changed");
  });
}

for (const fixture of baseline.fixtures.filter(fixture => fixture.config.createNamespace !== false)) {
  test(`${fixture.mode} refuses host references before BaseConstruct resolves public input`, () => {
    const plan = fixture.mode === "tng" ? tngTrusteePlan(fixture.config) : trusteePlan(fixture.config);
    const reviewed = { canonicalPodSha256: plan.canonicalPodSha256, policyRego: baseline.policyRego };
    const policy = fixture.mode === "tng" ? tngTrusteeInitData(fixture.config, reviewed) : trusteeInitData(fixture.config, reviewed);
    const envName = "NEBULA_TRUSTEE_TEST_PUBLIC_INPUT";
    const previous = process.env[envName];
    // This would resolve to valid public input and deploy if the guard ran
    // after BaseConstruct. No secret resolver process is needed for this test.
    process.env[envName] = fixture.mode === "tng" ? fixture.config.ownerPublicKeyPem : fixture.config.bootstrap.certificatePem;
    const reference = `ref+env://${envName}`;
    const chart = new Chart(new App(), "test");
    try {
      if (fixture.mode === "tng") {
        const config = { ...fixture.config, ownerPublicKeyPem: reference };
        assert.throws(() => tngTrusteePlan(config), /host-side ref\+ resolution is forbidden/);
        assert.throws(() => new TngTrustee(chart, "trustee", { ...config, policy }), /host-side ref\+ resolution is forbidden/);
      } else {
        const config = { ...fixture.config, bootstrap: { ...fixture.config.bootstrap, certificatePem: reference } };
        assert.throws(() => trusteePlan(config), /host-side ref\+ resolution is forbidden/);
        assert.throws(() => new Trustee(chart, "trustee", { ...config, policy }), /host-side ref\+ resolution is forbidden/);
      }
      assert.deepEqual(chart.toJson(), [], "refused configuration must not create resources");
    } finally {
      if (previous === undefined) delete process.env[envName];
      else process.env[envName] = previous;
    }
  });
}

test("TNG binding rejects altered native configuration even with a recomputed artifact hash", () => {
  const fixture = baseline.fixtures.find(fixture => fixture.mode === "tng");
  assert.ok(fixture?.mode === "tng");
  const config = fixture.config;
  const plan = tngTrusteePlan(config);
  const policy = tngTrusteeInitData(config, { canonicalPodSha256: plan.canonicalPodSha256, policyRego: baseline.policyRego });
  const changes: ((document: TomlTable) => void)[] = [
    document => { document.algorithm = "sha512"; },
    document => { document.extra = "unexpected"; },
    document => { (document.data as TomlTable)["cdh.toml"] = "unexpected bootstrap"; },
    document => { (document.data as TomlTable)["aa.toml"] = '[log]\nlevel = "debug"\n'; },
    document => { (document.data as TomlTable)["trustee.template.sha256"] = "0".repeat(64); },
    document => { (document.data as TomlTable)["policy.rego"] = ["not a policy"]; },
    document => { (document.data as TomlTable)["policy.rego"] = baseline.policyRego + "\nExecProcessRequest if { true }\n"; },
  ];
  for (const change of changes) {
    const document = parse(initDataDocument(policy.ccInitData).toString("utf8"));
    change(document);
    const bytes = Buffer.from(stringify(document));
    const altered = { ...policy, ccInitData: gzipSync(bytes).toString("base64"), initDataSha256: sha256Hex(bytes) };
    const chart = new Chart(new App(), "test");
    assert.throws(() => new TngTrustee(chart, "trustee", { ...config, policy: altered }), /unexpected InitData|unconditionally deny/);
    assert.deepEqual(chart.toJson(), []);
  }
});
